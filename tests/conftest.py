def local_s3_kwargs(backend: str) -> dict:
    endpoint, access_key, secret_key = S3_BACKENDS[backend]
    env = backend.upper()
    return dict(
        endpoint=os.environ.get(f"CAPO_{env}_ENDPOINT", endpoint),
        region="us-east-1",
        force_path_style=True,
        credentials=Credentials(
            access_key=os.environ.get(f"CAPO_{env}_ACCESS_KEY", access_key),
            secret_key=os.environ.get(f"CAPO_{env}_SECRET_KEY", secret_key),
        ),
    )


@pytest.fixture(scope="session", params=list(S3_BACKENDS))
def s3_backend(request: pytest.FixtureRequest) -> str:
    """Name of the local S3-compatible backend; skips when its server is down."""
    name = request.param
    endpoint = local_s3_kwargs(name)["endpoint"]
    if not _reachable(endpoint):
        pytest.skip(f"{name} is not listening at {endpoint} (docker compose -f tests/docker-compose.yml up -d)")
    return name


def unique_name(prefix: str = "capotest") -> str:
    return f"{prefix}-{uuid.uuid4().hex[:10]}"


def purge_bucket(s3: S3Client, name: str) -> None:
    """Remove every upload, version and delete marker, then the bucket."""
    for upload in s3.list_multipart_uploads(name).get("uploads", []):
        s3.abort_multipart_upload(name, upload["key"], upload_id=upload["upload_id"])
    while True:
        out = s3.list_object_versions(name)
        versions = out.get("versions", []) + out.get("delete_markers", [])
        if not versions:
            break
        for v in versions:
            s3.delete_object(name, v["key"], version_id=v["version_id"])
    s3.delete_bucket(name)


@pytest.fixture(scope="session")
def s3(s3_backend: str) -> Iterator[S3Client]:
    with S3Client(**local_s3_kwargs(s3_backend)) as client:
        yield client


@pytest.fixture
async def async_s3(s3_backend: str) -> AsyncIterator[AsyncS3Client]:
    async with AsyncS3Client(**local_s3_kwargs(s3_backend)) as client:
        yield client


@pytest.fixture
def bucket(s3: S3Client) -> Iterator[str]:
    """A fresh bucket on the local server, purged after the test."""
    name = unique_name()
    s3.create_bucket(name)
    try:
        yield name
    finally:
        purge_bucket(s3, name)
