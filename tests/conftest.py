def local_s3_settings(backend: str) -> tuple[str, str, str]:
    """(endpoint, access key, secret key) of a local backend, with env overrides."""
    endpoint, access_key, secret_key = S3_BACKENDS[backend]
    env = backend.upper()
    return (
        os.environ.get(f"CAPO_{env}_ENDPOINT", endpoint),
        os.environ.get(f"CAPO_{env}_ACCESS_KEY", access_key),
        os.environ.get(f"CAPO_{env}_SECRET_KEY", secret_key),
    )


def make_s3_client(
    backend: str, credentials: Credentials | None = None, http_handler: BaseHandler | None = None
) -> S3Client:
    """A client for ``backend``; AWS uses the default credentials chain unless given some."""
    if backend == "aws":
        return S3Client(region=AWS_REGION, credentials=credentials, http_handler=http_handler)
    endpoint, access_key, secret_key = local_s3_settings(backend)
    if credentials is None:
        credentials = Credentials(access_key=access_key, secret_key=secret_key)
    return S3Client(
        endpoint=endpoint,
        region="us-east-1",
        force_path_style=True,
        credentials=credentials,
        http_handler=http_handler,
    )


def make_async_s3_client(
    backend: str, credentials: Credentials | None = None, http_handler: AsyncBaseHandler | None = None
) -> AsyncS3Client:
    """Async twin of :func:`make_s3_client`."""
    if backend == "aws":
        return AsyncS3Client(region=AWS_REGION, credentials=credentials, http_handler=http_handler)
    endpoint, access_key, secret_key = local_s3_settings(backend)
    if credentials is None:
        credentials = Credentials(access_key=access_key, secret_key=secret_key)
    return AsyncS3Client(
        endpoint=endpoint,
        region="us-east-1",
        force_path_style=True,
        credentials=credentials,
        http_handler=http_handler,
    )


@pytest.fixture(
    scope="session",
    params=[pytest.param(name, marks=pytest.mark.third_party_services) for name in S3_BACKENDS]
    + [pytest.param("aws", marks=pytest.mark.paid)],
)
def s3_backend(request: pytest.FixtureRequest) -> str:
    """Backend name; a local backend skips when its server is down."""
    name = request.param
    if name != "aws":
        endpoint = local_s3_settings(name)[0]
        if not _reachable(endpoint):
            pytest.skip(f"{name} is not listening at {endpoint} (docker compose -f tests/docker-compose.yml up -d)")
    return name


def create_bucket_kwargs(backend: str) -> dict:
    """AWS needs a LocationConstraint outside us-east-1; the local servers ignore it."""
    if backend == "aws":
        return dict(create_bucket_configuration={"location_constraint": AWS_REGION})
    return {}


def unique_name(prefix: str = "capotest") -> str:
    return f"{prefix}-{uuid.uuid4().hex[:10]}"


def purge_bucket(s3: S3Client, name: str) -> None:
    """Remove every upload, version and delete marker, then the bucket."""
    for upload in s3.list_multipart_uploads(name).get("uploads", []):
        s3.abort_multipart_upload(name, upload["key"], upload_id=upload["upload_id"])
    while True:
        out = s3.list_object_versions(name)
        versions = out.get("versions", []) + out.get("delete_markers", [])
        if not versions:
            break
        for v in versions:
            s3.delete_object(name, v["key"], version_id=v["version_id"])
    s3.delete_bucket(name)


class _SyncView:
    """Sync calls on an async client, for the setup fixtures on Pyodide (see ``s3``)."""

    def __init__(self, client: AsyncS3Client) -> None:
        self._client = client

    def __getattr__(self, name: str) -> Callable[..., Any]:
        from pyodide.ffi import run_sync  # ty: ignore[unresolved-import]

        method = getattr(self._client, name)
        return lambda *args, **kwargs: run_sync(method(*args, **kwargs))


@pytest.fixture(scope="session")
def s3(s3_backend: str) -> Iterator[S3Client]:
    if sys.platform == "emscripten":
        # The sync client cannot run on Pyodide (no sync HTTP), so the sync setup
        # fixtures (bucket, ...) drive the async client through pyodide.ffi.run_sync.
        from pyodide.ffi import run_sync  # ty: ignore[unresolved-import]

        aclient = make_async_s3_client(s3_backend)
        run_sync(aclient.__aenter__())
        try:
            yield _SyncView(aclient)  # type: ignore[misc]
        finally:
            run_sync(aclient.__aexit__(None, None, None))
    else:
        with make_s3_client(s3_backend) as client:
            yield client


