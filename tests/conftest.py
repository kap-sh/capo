async def agather(fn: Callable[[], Coroutine[Any, Any, T]], n: int) -> list[T]:
    """Run ``fn`` ``n`` times concurrently in a task group; results in call order."""
    results: list[T] = []
    slots: dict[int, T] = {}

    async def one(i: int) -> None:
        slots[i] = await fn()

    async with anyio.create_task_group() as tg:
        for i in range(n):
            tg.start_soon(one, i)
    results = [slots[i] for i in range(n)]
    return results


def gather(fn: Callable[[], T], n: int) -> list[T]:
    """Sync twin of :func:`agather`: ``n`` calls on ``n`` threads."""
    with ThreadPoolExecutor(max_workers=n) as pool:
        return list(pool.map(lambda _: fn(), range(n)))


async def aread_body(get_object_ctx) -> bytes:
    """Drain the body of a ``get_object`` call: ``await aread_body(client.get_object(b, k))``."""
    async with get_object_ctx as obj:
        return b"".join([chunk async for chunk in obj["body"]])


def read_body(get_object_ctx) -> bytes:
    """Sync twin of :func:`aread_body`."""
    with get_object_ctx as obj:
        return b"".join(obj["body"])


def parts_of(data: bytes, size: int = 64 * 1024) -> list[bytes]:
    return [data[i : i + size] for i in range(0, len(data), size)]


async def astream(parts: list[bytes]) -> AsyncIterator[bytes]:
    """An async one-shot body; ``stream`` is the sync twin."""
    for part in parts:
        yield part


def stream(parts: list[bytes]) -> Iterator[bytes]:
    for part in parts:
        yield part


def crc32_b64(data: bytes) -> str:
    """CRC32 the way S3 reports it: big-endian, base64."""
    return base64.b64encode(zlib.crc32(data).to_bytes(4, "big")).decode()


