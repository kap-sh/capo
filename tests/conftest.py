def _reachable(url: str) -> bool:
    if sys.platform == "emscripten":
        # Pyodide has no sockets; the clients reach the server through JS fetch instead.
        from js import fetch  # ty: ignore[unresolved-import]
        from pyodide.ffi import run_sync  # ty: ignore[unresolved-import]

        try:
            run_sync(fetch(url))
            return True
        except Exception:
            return False
    parsed = urlparse(url)
    port = parsed.port or (443 if parsed.scheme == "https" else 80)
    try:
        with socket.create_connection((parsed.hostname or "localhost", port), timeout=0.5):
            return True
    except OSError:
        return False


def pytest_collection_modifyitems(config: pytest.Config, items: list[pytest.Item]) -> None:
    paid = os.environ.get("CAPO_PAID") == "1"
    for item in items:
        if "paid" in item.keywords and not paid:
            item.add_marker(pytest.mark.skip(reason="set CAPO_PAID=1 to run tests that cost money"))
    if sys.platform == "emscripten":
        # Pyodide (scripts/test-pyodide.sh) has no threads, so only the async tests run there.
        keep = [item for item in items if inspect.iscoroutinefunction(getattr(item, "function", None))]
        deselected = [item for item in items if item not in keep]
        if deselected:
            config.hook.pytest_deselected(items=deselected)
        items[:] = keep


